#!/usr/bin/env python3
"""
NKZ Factory Tool — provisioning station for field devices.

Usage:
    python flash_tool.py provision \
        --uuid <DEVICE_UUID> \
        --type rover|gateway|sensor \
        --tenant <TENANT_ID> \
        --api-url https://<api-host> \
        --token <PLATFORM_ADMIN_ACCESS_TOKEN> \
        --out-dir ./output/<uuid>/

What it does:
    1. Registers the device for the tenant (POST /api/vpn/factory/register-device)
       and receives its claim code.
    2. Generates an RSA-2048 key pair and a CSR locally (CN = device UUID,
       OU = device type; the CN is the device's MQTT identity on the mTLS listener).
    3. Has the CSR signed by the IoT CA (POST /api/vpn/factory/sign-csr).
    4. Writes to --out-dir:
        device.key       private key (mode 0600 — flash it, then destroy the local copy)
        device.crt       certificate signed by the IoT CA
        ca.crt           IoT CA certificate
        claim_code.txt   print on the chassis
        nkz-device.json  {device_uuid, device_type, tenant_id}
       and for sensors a C header (nkz_credentials.h) with the PEMs.

Both calls go through the platform API gateway with a PlatformAdmin access
token; the claim code is the only activation mechanism for the tenant.
"""

import argparse
import json
import os
import sys
import textwrap
import uuid as uuidlib
from pathlib import Path

import httpx
from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID

DEVICE_TYPES = ("rover", "gateway", "sensor")


def generate_keypair() -> tuple[rsa.RSAPrivateKey, str]:
    private_key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    key_pem = private_key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.TraditionalOpenSSL,
        encryption_algorithm=serialization.NoEncryption(),
    ).decode("utf-8")
    return private_key, key_pem


def generate_csr(private_key: rsa.RSAPrivateKey, device_uuid: str, device_type: str) -> str:
    csr = (
        x509.CertificateSigningRequestBuilder()
        .subject_name(x509.Name([
            x509.NameAttribute(NameOID.COMMON_NAME, device_uuid),
            x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Nekazari"),
            x509.NameAttribute(NameOID.ORGANIZATIONAL_UNIT_NAME, device_type),
        ]))
        .sign(private_key, hashes.SHA256())
    )
    return csr.public_bytes(serialization.Encoding.PEM).decode("utf-8")


def _post(api_url: str, path: str, token: str, body: dict, expected: tuple[int, ...]) -> dict:
    r = httpx.post(
        f"{api_url.rstrip('/')}/api/vpn{path}",
        json=body,
        headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"},
        timeout=60,
    )
    if r.status_code not in expected:
        detail = r.json().get("detail", r.text) if r.headers.get("content-type", "").startswith("application/json") else r.text
        print(f"ERROR {path}: HTTP {r.status_code} {detail}", file=sys.stderr)
        sys.exit(1)
    return r.json()


def write_esp32_header(out_dir: Path, key_pem: str, cert_pem: str, ca_pem: str) -> None:
    def c_string(pem: str) -> str:
        return "\n".join(f'    "{line}\\n"' for line in pem.strip().split("\n"))

    header = textwrap.dedent("""\
        // NKZ device credentials — generated by the factory tool.
        // DO NOT COMMIT: contains the device private key.
        #pragma once

        static const char* NKZ_DEVICE_PRIVATE_KEY = \\
        {key};

        static const char* NKZ_DEVICE_CERTIFICATE = \\
        {cert};

        static const char* NKZ_CA_CERTIFICATE = \\
        {ca};
        """).format(key=c_string(key_pem), cert=c_string(cert_pem), ca=c_string(ca_pem))
    path = out_dir / "nkz_credentials.h"
    path.write_text(header)
    os.chmod(path, 0o600)


def provision(args: argparse.Namespace) -> None:
    device_uuid = str(uuidlib.UUID(args.uuid))  # canonical form, fails fast on garbage
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    print(f"Provisioning {device_uuid} ({args.type}) for tenant {args.tenant}")

    body = {"device_uuid": device_uuid, "device_type": args.type, "tenant_id": args.tenant}
    if args.name:
        body["display_name"] = args.name
    # 201 on first registration, 200 when the same device is registered again
    # (e.g. a previous run failed at signing): the code is the same either way.
    claim_code = _post(args.api_url, "/factory/register-device", args.token, body, (200, 201))["claim_code"]
    (out_dir / "claim_code.txt").write_text(f"{claim_code}\n")  # kept even if signing fails below
    print(f"1. Registered. Claim code: {claim_code}")

    private_key, key_pem = generate_keypair()
    csr_pem = generate_csr(private_key, device_uuid, args.type)
    signed = _post(args.api_url, "/factory/sign-csr", args.token,
                   {"csr_pem": csr_pem, "device_uuid": device_uuid}, (200,))
    print("2. Certificate signed.")

    key_path = out_dir / "device.key"
    key_path.write_text(key_pem)
    os.chmod(key_path, 0o600)
    (out_dir / "device.crt").write_text(signed["certificate_pem"])
    (out_dir / "ca.crt").write_text(signed["ca_pem"])
    (out_dir / "nkz-device.json").write_text(json.dumps(
        {"device_uuid": device_uuid, "device_type": args.type, "tenant_id": args.tenant}, indent=2) + "\n")
    if args.type == "sensor":
        write_esp32_header(out_dir, key_pem, signed["certificate_pem"], signed["ca_pem"])

    print(f"3. Written to {out_dir}/")
    print(f"   Claim code: {claim_code}   <- print on the chassis")
    print("   device.key is the device's private key: flash it, then destroy the local copy.")


def main() -> None:
    parser = argparse.ArgumentParser(description="NKZ Factory Tool")
    sub = parser.add_subparsers(dest="command")
    p = sub.add_parser("provision", help="Register a device, sign its certificate, write the bundle")
    p.add_argument("--uuid", required=True, help="Device UUID")
    p.add_argument("--type", required=True, choices=DEVICE_TYPES)
    p.add_argument("--tenant", required=True, help="Tenant ID the device is built for")
    p.add_argument("--api-url", required=True, help="Platform API origin")
    p.add_argument("--token", required=True, help="PlatformAdmin access token")
    p.add_argument("--out-dir", required=True, help="Output directory")
    p.add_argument("--name", help="Display name")
    args = parser.parse_args()
    if args.command == "provision":
        provision(args)
    else:
        parser.print_help()
        sys.exit(1)


if __name__ == "__main__":
    main()
